// Generates src/share/viewerFonts.ts: the app's Rubik font files (public/fonts) as base64, so the client page can
// serve them from its own origin (/c/_/...) with no third-party request. Run after changing public/fonts:
//   node worker/scripts/gen-viewer-fonts.mjs
// scripts/viewer-fonts.test.ts (root suite) fails if the generated module and public/fonts drift apart.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const ARABIC =
  'U+0600-06FF, U+0750-077F, U+0870-0891, U+0897-08E1, U+08E3-08FF, U+200C-200E, U+2010-2011, U+204F, U+2E41, U+FB50-FDFF, U+FE70-FE74, U+FE76-FEFC';
const LATIN =
  'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';

const files = [
  { name: 'rubik-arabic', range: ARABIC },
  { name: 'rubik-latin', range: LATIN },
].map(({ name, range }) => {
  const bytes = readFileSync(`${root}public/fonts/${name}.woff2`);
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 10);
  // The hash in the path makes the URL immutable: a new font file gets a new URL, so caches never go stale.
  return { path: `/c/_/${name}.${hash}.woff2`, range, base64: bytes.toString('base64') };
});

const body = files
  .map((f) => `  {\n    path: '${f.path}',\n    range: '${f.range}',\n    base64:\n      '${f.base64}',\n  },`)
  .join('\n');
writeFileSync(
  `${root}worker/src/share/viewerFonts.ts`,
  `// GENERATED by worker/scripts/gen-viewer-fonts.mjs from public/fonts/rubik-*.woff2 — do not edit by hand.
// Rubik (SIL OFL 1.1, see public/fonts/OFL-Rubik.txt): the client page uses the app's font, served same-origin.
export interface ViewerFont {
  path: string;
  range: string;
  base64: string;
}

export const VIEWER_FONTS: readonly ViewerFont[] = [
${body}
];
`,
);
console.log(files.map((f) => `${f.path} ${Math.round((f.base64.length * 3) / 4 / 1024)} KB`).join('\n'));
